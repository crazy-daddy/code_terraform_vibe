"""
Extract the research thresholds into scripts/4_controlpanel/lib/research_thresholds.py.

    python devtools/game_update/extract_research.py          # regenerate the module
    python devtools/game_update/extract_research.py --check  # exit 1 when the module is stale

Source: docs/database/research_catalog.md (the game's own research page export).
Each entry is a heading `##### Name` with the research id in backticks, followed by a table with a
`Threshold` row (`<Pillar> <value>`) and a `Tech id` row (the save file's id).
The module is committed and read in game by lib/game_phase.py: the research
component exposes only is_unlocked()/unlocked(), no thresholds, so the fixed
limits come from the catalog (information policy: fixed absolute limits are
allowed). Regenerate after a game update; tests/test_research_thresholds.py
compares the module with the catalog.
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
CATALOG = REPO / "docs" / "database" / "research_catalog.md"
MODULE = REPO / "scripts" / "4_controlpanel" / "lib" / "research_thresholds.py"

# Catalog pillar label -> pillar id (terraforming.pillars() ids; "tp" = nocturna.total_tp()).
PILLAR_LABELS = {
    "Terraform Index": "tp",
    "Temperature": "temperature",
    "Oxygen": "oxygen",
    "Pressure": "pressure",
    "Biomass": "biomass",
    "Plants": "plants",
    "Wildlife": "wildlife",
}
HEADING = re.compile(r"^##### (?P<name>.+?) `(?P<id>research_[a-z0-9_]+)`")
THRESHOLD = re.compile(r"^\| Threshold \| (?P<label>[A-Za-z ]+?) (?P<value>[0-9][0-9,.]*) \|")
TECH = re.compile(r"^\| Tech id \| (?P<tech>[a-z0-9_]+) \|")
ANY_HEADING = re.compile(r"^##### .*`research_", re.MULTILINE)  # every research heading, strict or not


def parse(text):
    """[(research_id, name, pillar, value, tech_id)] in catalog order."""
    rows = []
    current = None
    seen = set()
    for line in text.splitlines():
        head = HEADING.match(line)
        if head:
            if head.group("id") in seen:
                raise ValueError(f"{head.group('id')}: duplicate entry")
            seen.add(head.group("id"))
            current = {"id": head.group("id"), "name": head.group("name").strip()}
            rows.append(current)
            continue
        if current is None:
            continue
        found = THRESHOLD.match(line)
        if found:
            if "pillar" in current:
                raise ValueError(f"{current['id']}: second Threshold row")
            label = found.group("label").strip()
            if label not in PILLAR_LABELS:
                raise ValueError(f"{current['id']}: unknown pillar label {label!r}")
            number = found.group("value").replace(",", "")
            value = float(number)
            current["pillar"] = PILLAR_LABELS[label]
            current["value"] = int(value) if value == int(value) else value
            continue
        found = TECH.match(line)
        if found:
            if "tech" in current:
                raise ValueError(f"{current['id']}: second Tech id row")
            current["tech"] = found.group("tech")
    mentioned = len(ANY_HEADING.findall(text))
    if mentioned != len(rows):
        raise ValueError(f"{mentioned} research headings in the catalog, {len(rows)} parsed: heading format changed")
    out = []
    for row in rows:
        missing = [key for key in ("pillar", "value", "tech") if key not in row]
        if missing:
            raise ValueError(f"{row['id']}: missing {missing}")
        out.append((row["id"], row["name"], row["pillar"], row["value"], row["tech"]))
    return out


def render(rows):
    lines = [
        "# Generated by devtools/game_update/extract_research.py from docs/database/research_catalog.md.",
        "# Do not edit: regenerate after a game update (tests/test_research_thresholds.py checks it).",
        "#",
        "# THRESHOLDS: research id -> (pillar, threshold, save tech id). Pillar ids are the",
        '# terraforming.pillars() ids plus "tp" for nocturna.total_tp(). research.is_unlocked()',
        "# is the truth once a threshold is reached; these values only say how far away it is.",
        "",
        "THRESHOLDS = {",
    ]
    for research_id, name, pillar, value, tech in rows:
        lines.append(f'    "{research_id}": ("{pillar}", {value!r}, "{tech}"),  # {name}')
    lines.append("}")
    lines.append("")
    lines.append("# Catalog order (the Research page order).")
    lines.append("ORDER = (")
    for research_id, _name, _pillar, _value, _tech in rows:
        lines.append(f'    "{research_id}",')
    lines.append(")")
    lines.append("")
    lines.append("# Save tech id -> research id (replay tooling reads state.unlockedTech).")
    lines.append("TECH_TO_RESEARCH = {")
    for research_id, _name, _pillar, _value, tech in rows:
        lines.append(f'    "{tech}": "{research_id}",')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the module differs from the catalog")
    parser.add_argument("--catalog", default=str(CATALOG))
    parser.add_argument("--out", default=str(MODULE))
    args = parser.parse_args()
    text = render(parse(Path(args.catalog).read_text("utf-8")))
    out = Path(args.out)
    if args.check:
        current = out.read_text("utf-8") if out.exists() else ""
        if current != text:
            print(f"stale: {out} differs from {args.catalog}; rerun without --check")
            return 1
        print("up to date")
        return 0
    out.write_text(text, "utf-8", newline="\n")
    print(f"wrote {out}: {text.count(chr(10))} lines, {len(parse(Path(args.catalog).read_text('utf-8')))} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
